#!/usr/bin/env Rscript
# Generate man/*.Rd from scripts/rd_topics.R without roxygen2.
# Usage sections are built from the functions' actual formals, so they cannot
# drift from the code. Run from the repository root: Rscript scripts/build_rd.R

suppressMessages(pkgload::load_all(".", quiet = TRUE, export_all = FALSE))
namespace <- asNamespace("OpenPVA")
source("scripts/rd_topics.R", local = TRUE)

escape <- function(text) {
  gsub("%", "\\\\%", text, fixed = FALSE)
}

usage_for <- function(name) {
  fn <- get(name, envir = namespace)
  arguments <- formals(fn)
  pieces <- vapply(names(arguments), function(argument) {
    if (identical(arguments[[argument]], quote(expr = ))) {
      argument
    } else {
      paste0(
        argument, " = ",
        paste(deparse(arguments[[argument]], width.cutoff = 500L), collapse = " ")
      )
    }
  }, character(1))
  one_line <- paste0(name, "(", paste(pieces, collapse = ", "), ")")
  if (nchar(one_line) <= 80L) {
    return(one_line)
  }
  paste0(name, "(\n  ", paste(pieces, collapse = ",\n  "), "\n)")
}

write_topic <- function(file, topic) {
  functions <- topic$functions
  arguments <- unique(unlist(lapply(functions, function(name) {
    names(formals(get(name, envir = namespace)))
  })))
  described <- c(topic$arguments, common_arguments)
  missing <- setdiff(arguments, names(described))
  if (length(missing)) {
    stop("topic ", file, " lacks argument text for: ", paste(missing, collapse = ", "))
  }
  unused <- setdiff(names(topic$arguments), arguments)
  if (length(unused)) {
    stop("topic ", file, " documents absent arguments: ", paste(unused, collapse = ", "))
  }
  usage <- vapply(functions, usage_for, character(1))
  lines <- c(
    "% Generated by scripts/build_rd.R from scripts/rd_topics.R; edit those files.",
    paste0("\\name{", file, "}"),
    paste0("\\alias{", unique(c(file, functions, topic$aliases)), "}"),
    paste0("\\title{", topic$title, "}"),
    "\\usage{",
    escape(paste(c(usage, topic$usage), collapse = "\n\n")),
    "}"
  )
  if (length(arguments)) {
    lines <- c(
      lines,
      "\\arguments{",
      vapply(arguments, function(argument) {
        name <- if (argument == "...") "\\dots" else argument
        paste0("\\item{", name, "}{", described[[argument]], "}")
      }, character(1)),
      "}"
    )
  }
  lines <- c(lines, "\\description{", topic$description, "}")
  if (!is.null(topic$details)) {
    lines <- c(lines, "\\details{", topic$details, "}")
  }
  lines <- c(lines, "\\value{", topic$value, "}")
  if (!is.null(topic$seealso)) {
    lines <- c(lines, "\\seealso{", topic$seealso, "}")
  }
  if (!is.null(topic$examples)) {
    lines <- c(lines, "\\examples{", escape(topic$examples), "}")
  }
  writeLines(lines, file.path("man", paste0(file, ".Rd")))
}

unlink(list.files("man", pattern = "\\.Rd$", full.names = TRUE))
dir.create("man", showWarnings = FALSE)
for (file in names(topics)) {
  write_topic(file, topics[[file]])
}
writeLines(c(
  "% Generated by scripts/build_rd.R from scripts/rd_topics.R; edit those files.",
  "\\name{print.pva_state}",
  "\\alias{print.pva_state}",
  "\\alias{print.pva_process}",
  "\\alias{print.pva_scenario}",
  "\\alias{print.pva_run}",
  "\\title{Print OpenPVA objects}",
  "\\usage{",
  "\\method{print}{pva_state}(x, ...)",
  "",
  "\\method{print}{pva_process}(x, ...)",
  "",
  "\\method{print}{pva_scenario}(x, ...)",
  "",
  "\\method{print}{pva_run}(x, ...)",
  "}",
  "\\arguments{",
  "\\item{x}{An OpenPVA state, process, scenario or run.}",
  "\\item{\\dots}{Ignored.}",
  "}",
  "\\description{One-line summaries of OpenPVA objects.}",
  "\\value{\\code{x}, invisibly.}"
), "man/print.pva_state.Rd")

documented <- unlist(lapply(topics, `[[`, "functions"))
exported <- getNamespaceExports("OpenPVA")
if (length(setdiff(exported, documented))) {
  stop("undocumented exports: ", paste(setdiff(exported, documented), collapse = ", "))
}
if (length(setdiff(documented, exported))) {
  stop("documented but not exported: ", paste(setdiff(documented, exported), collapse = ", "))
}
cat("wrote", length(topics) + 1L, "Rd files for", length(exported), "exports\n")
