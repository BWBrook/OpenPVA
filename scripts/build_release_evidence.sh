#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

RC_LABEL="${1:-rc1}"
if [[ ! "$RC_LABEL" =~ ^rc[0-9]+$ ]]; then
  echo "Usage: scripts/build_release_evidence.sh [rcN]" >&2
  exit 1
fi

VERSION="$(awk '/^Version:/{print $2; exit}' DESCRIPTION)"
if [[ -z "$VERSION" ]]; then
  echo "Could not read package version from DESCRIPTION" >&2
  exit 1
fi

OUT_DIR="artefacts/release_${VERSION}-${RC_LABEL}"
mkdir -p "$OUT_DIR"

echo "Building release evidence bundle at: $OUT_DIR"

echo "+ renv restore" | tee "$OUT_DIR/restore.log"
Rscript -e "renv::restore(prompt = FALSE)" 2>&1 | tee -a "$OUT_DIR/restore.log"

echo "+ lint" | tee "$OUT_DIR/lint.log"
Rscript -e "lints <- lintr::lint_package(); cat('n_lints=', length(lints), '\n', sep=''); print(lints); if (length(lints) > 0) quit(status = 1)" 2>&1 | tee -a "$OUT_DIR/lint.log"

echo "+ tests" | tee "$OUT_DIR/tests.log"
Rscript scripts/run_tests.R 2>&1 | tee -a "$OUT_DIR/tests.log"

echo "+ targets smoke" | tee "$OUT_DIR/targets_smoke.log"
Rscript -e "targets::tar_invalidate(names = c('sim_basic')); targets::tar_make(script = '_targets.R', store = '_targets', names = c('sim_basic'))" 2>&1 | tee -a "$OUT_DIR/targets_smoke.log"

echo "+ quarto render" | tee "$OUT_DIR/quarto_render.log"
quarto render quarto 2>&1 | tee -a "$OUT_DIR/quarto_render.log"

echo "+ build source tarball" | tee "$OUT_DIR/build_stdout.log"
R CMD build --no-build-vignettes . 2>&1 | tee -a "$OUT_DIR/build_stdout.log"

LATEST_TGZ="$(Rscript -e 'files <- Sys.glob("OpenPVA_*.tar.gz"); if (!length(files)) quit(status = 1); cat(files[which.max(file.info(files)[["mtime"]])])')"
cp -f "$LATEST_TGZ" "$OUT_DIR/$LATEST_TGZ"

echo "+ run R CMD check --as-cran" | tee "$OUT_DIR/check_stdout.log"
R CMD check --no-manual --as-cran "$LATEST_TGZ" 2>&1 | tee -a "$OUT_DIR/check_stdout.log"
cp -f OpenPVA.Rcheck/00check.log "$OUT_DIR/00check.log"

if [[ -d quarto/_site ]]; then
  find quarto/_site -type f | sort > "$OUT_DIR/quarto_output_manifest.txt"
else
  echo "quarto/_site not found" > "$OUT_DIR/quarto_output_manifest.txt"
fi

echo "+ generate toy scenario outputs" | tee "$OUT_DIR/toy_scenario.log"
OUT_DIR_ABS="$(cd "$OUT_DIR" && pwd)"
OUT_DIR="$OUT_DIR_ABS" Rscript - <<'RS' 2>&1 | tee -a "$OUT_DIR/toy_scenario.log"
pkgload::load_all(quiet = TRUE)
out_dir <- Sys.getenv("OUT_DIR")

sc <- scenario_spec(
  name = "release_toy",
  n_runs = 5,
  n_years = 12,
  init_fun = function() initialize_population(30),
  density_spec = density_spec(
    survival_fun = make_ceiling_density_fun(K = 40)
  ),
  harvest_quota = 1,
  seed = 20260209L
)
out <- run_scenario(sc)

saveRDS(out, file = file.path(out_dir, "toy_scenario_output.rds"))
write.csv(out$sim_output$summary, file = file.path(out_dir, "toy_scenario_summary.csv"), row.names = FALSE)
write.csv(out$sim_output$extinction, file = file.path(out_dir, "toy_scenario_extinction.csv"), row.names = FALSE)

ext <- summarise_extinction(out$sim_output)
cat("Toy extinction summary:\n")
print(ext)
RS

cat > "$OUT_DIR/toy_interpretation_note.txt" <<'TXT'
Toy scenario sanity check:
- Seeded run completed with deterministic outputs.
- Summary and extinction tables were written without missing required columns.
- No runtime errors observed in toy scenario generation.
TXT

cat > "$OUT_DIR/README.md" <<TXT
# Release evidence bundle

Bundle: ${OUT_DIR}
Date: $(date -u '+%Y-%m-%dT%H:%M:%SZ')

Generated by: 
- scripts/build_release_evidence.sh ${RC_LABEL}

Contents:
- restore.log
- lint.log
- tests.log
- targets_smoke.log
- quarto_render.log
- build_stdout.log
- check_stdout.log
- 00check.log
- ${LATEST_TGZ}
- quarto_output_manifest.txt
- toy_scenario_output.rds
- toy_scenario_summary.csv
- toy_scenario_extinction.csv
- toy_scenario.log
- toy_interpretation_note.txt

Non-publishing scope:
- This automation does not create tags, publish releases, or upload to CRAN.
TXT

echo "Release evidence bundle complete: $OUT_DIR"
